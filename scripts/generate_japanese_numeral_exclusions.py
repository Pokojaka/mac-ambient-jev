#!/usr/bin/env python3
"""Build the whole-phrase exclusion list for the kanji-numeral display conversion.

`candidates` lists the Wikipedia and Wiktionary titles in which the display rule
would rewrite a kanji numeral. Those titles are labelled EXCLUDE or KEEP by hand
or by an LLM into tools/numeral-exclusions/labels.tsv. `swift` turns the EXCLUDE
labels into JapaneseNumeralExclusionPhrases.swift.
"""

import argparse
import gzip
import re
import sys
from pathlib import Path

NUMERALS = "〇零一二三四五六七八九十百千万億"
RUN = re.compile(f"[{NUMERALS}]+(?:点[{NUMERALS}]+)?")
DISAMBIGUATION = re.compile(r" \([^()]*\)$")
LABELS = {"EXCLUDE", "KEEP"}


def is_kanji(character: str) -> bool:
    code = ord(character)
    return (
        character == "々"
        or 0x3400 <= code <= 0x4DBF
        or 0x4E00 <= code <= 0x9FFF
        or 0xF900 <= code <= 0xFAFF
        or 0x20000 <= code <= 0x3134F
    )


def blocks(character: str) -> bool:
    return is_kanji(character) or character in "0123456789０１２３４５６７８９.．"


def would_convert(title: str) -> bool:
    for match in RUN.finditer(title):
        before = title[match.start() - 1] if match.start() > 0 else ""
        after = title[match.end()] if match.end() < len(title) else ""
        # Fractions such as 三分の一 stay kanji on both sides.
        if title[match.end():match.end() + 2] == "分の":
            continue
        if title[max(0, match.start() - 2):match.start()] == "分の":
            continue
        if not (before and blocks(before)) and not (after and blocks(after)):
            return True
    return False


def read_titles(dump: Path):
    with gzip.open(dump, "rt", encoding="utf-8") as lines:
        header = next(lines).rstrip("\n")
        if header != "page_title":
            raise ValueError(f"{dump}: expected a page_title header, got {header!r}")
        for line in lines:
            yield line.rstrip("\n").replace("_", " ")


def candidates(dumps: list[Path], output: Path) -> None:
    found: dict[str, None] = {}
    for dump in dumps:
        for title in read_titles(dump):
            if would_convert(title):
                found[title] = None
    output.write_text("".join(f"{title}\n" for title in found), encoding="utf-8")
    print(f"{len(found)} candidates", file=sys.stderr)


def read_labels(path: Path) -> list[tuple[str, str]]:
    rows = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        label, separator, title = line.partition("\t")
        if not separator or label not in LABELS or not title:
            raise ValueError(f"{path}:{number}: expected EXCLUDE or KEEP, a tab, and a title")
        rows.append((label, title))
    return rows


def exclusion_phrases(rows: list[tuple[str, str]]) -> list[str]:
    phrases = set()
    for label, title in rows:
        if label != "EXCLUDE":
            continue
        # A disambiguation suffix such as " (曖昧さ回避)" never appears in speech.
        phrase = DISAMBIGUATION.sub("", title)
        if not any(character in NUMERALS for character in phrase):
            continue
        # A bare number left after the suffix, as in 一 (緑茶飲料), names something
        # else; only titles labelled as a numeral word themselves (九九) are kept.
        if phrase != title and all(character in NUMERALS for character in phrase):
            continue
        phrases.add(phrase)
    return sorted(phrases)


def swift_literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def swift_source(phrases: list[str]) -> str:
    body = "".join(f"        {swift_literal(phrase)},\n" for phrase in phrases)
    return (
        "// Generated by scripts/generate_japanese_numeral_exclusions.py from\n"
        "// tools/numeral-exclusions/labels.tsv. Do not edit by hand.\n"
        "internal enum JapaneseNumeralExclusionPhrases {\n"
        "    static let phrases: [String] = [\n"
        f"{body}"
        "    ]\n"
        "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    find = commands.add_parser("candidates", help="list titles the display rule would rewrite")
    find.add_argument("--dump", type=Path, action="append", required=True,
                      help="an all-titles-in-ns0.gz dump; repeat for each wiki")
    find.add_argument("--output", type=Path, required=True)
    generate = commands.add_parser("swift", help="write the Swift phrase list")
    generate.add_argument("--labels", type=Path, required=True)
    generate.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()

    if arguments.command == "candidates":
        candidates(arguments.dump, arguments.output)
    else:
        phrases = exclusion_phrases(read_labels(arguments.labels))
        arguments.output.write_text(swift_source(phrases), encoding="utf-8")
        print(f"{len(phrases)} phrases", file=sys.stderr)


if __name__ == "__main__":
    main()
