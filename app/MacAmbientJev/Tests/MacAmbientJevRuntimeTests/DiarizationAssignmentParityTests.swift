@available(macOS 14.0, *)
private func assignmentScoreCase(
    name: String,
    construction: String,
    flatScores: [Double],
    rows: Int,
    columns: Int
) throws -> [String: Any] {
    try #require(rows > 0 && columns > 0 && flatScores.count == rows * columns, "Invalid score case dimensions for \(name)")
    var finiteScores = flatScores
    var nonfinite: [[String: Any]] = []
    for index in flatScores.indices where !flatScores[index].isFinite {
        let value = flatScores[index]
        let kind: String
        if value.isNaN {
            kind = "nan"
        } else if value == .infinity {
            kind = "positiveInfinity"
        } else {
            kind = "negativeInfinity"
        }
        nonfinite.append(["index": index, "kind": kind])
        finiteScores[index] = 0
    }
    var reconstructedScores = finiteScores
    for patch in nonfinite {
        guard let index = patch["index"] as? Int, let kind = patch["kind"] as? String else {
            throw DiarizationParityOracleError.invalidTensor("\(name): malformed generated nonfinite score patch")
        }
        switch kind {
        case "nan": reconstructedScores[index] = .nan
        case "positiveInfinity": reconstructedScores[index] = .infinity
        case "negativeInfinity": reconstructedScores[index] = -.infinity
        default: throw DiarizationParityOracleError.invalidTensor("\(name): unsupported generated nonfinite score kind \(kind)")
        }
    }
    let matrix = (0..<rows).map { row in
        Array(reconstructedScores[(row * columns)..<((row + 1) * columns)])
    }
    let assignments = ConstrainedClusterAssignment.assign(
        scores: matrix,
        chunkIndices: Array(repeating: 0, count: rows)
    )
    let directHungarian = HungarianAssignment.maxScoreAssignment(scores: matrix).map { $0 >= 0 ? $0 : -2 }
    try #require(assignments == directHungarian, "Constrained assignment disagrees with direct Hungarian for \(name)")
    return [
        "name": name,
        "construction": construction,
        "scores": try DiarizationParityOracle.tensor(finiteScores, shape: [rows, columns]),
        "nonfinite": nonfinite,
        "expectedAssignments": assignments,
    ]
}

