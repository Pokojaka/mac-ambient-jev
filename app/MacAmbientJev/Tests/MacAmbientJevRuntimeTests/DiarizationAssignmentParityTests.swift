@available(macOS 14.0, *)
private func assignmentEmbeddingCase(
    manager: OfflineDiarizerManager,
    config: OfflineDiarizerConfig,
    name: String,
    construction: String,
    embeddings inputEmbeddings: [[Double]],
    nonfinite suppliedPatches: [[String: Any]],
    activeSlots: [Int],
    centroids: [[Double]],
    piSlots: Int
) throws -> [String: Any] {
    try #require(inputEmbeddings.count == 3, "Embedding fixture must contain exactly three rows")
    guard let dimension = inputEmbeddings.first?.count else {
        throw DiarizationParityOracleError.invalidTensor("\(name): embeddings must not be empty")
    }
    try #require(dimension > 0 && inputEmbeddings.allSatisfy { $0.count == dimension }, "Embedding rows must share a positive dimension")
    try #require(centroids.count >= 2 && centroids.count == piSlots && centroids.allSatisfy { $0.count == dimension }, "Constrained embedding fixtures require at least two dimension-matched centroids and pi slots")
    try #require(activeSlots == activeSlots.sorted() && activeSlots.allSatisfy { $0 >= 0 && $0 < 3 }, "Active feature slots must be a sorted subset of the three stored rows")
    try #require(config.clustering.constrainedAssignment, "Embedding manager fixture requires constrained assignment config")

    let pi = Array(repeating: 1.0 / Double(piSlots), count: piSlots)
    let gamma = (0..<piSlots).map { row in
        (0..<piSlots).map { $0 == row ? 1.0 : 0.0 }
    }
    let initialClusters = Array(0..<piSlots)
    let flattenedInput = inputEmbeddings.flatMap { $0 }
    var finiteInput = flattenedInput
    for patch in suppliedPatches {
        guard let index = patch["index"] as? Int, index >= 0, index < finiteInput.count,
            let kind = patch["kind"] as? String
        else {
            throw DiarizationParityOracleError.invalidTensor("\(name): malformed nonfinite input patch")
        }
        switch kind {
        case "nan": finiteInput[index] = .nan
        case "positiveInfinity": finiteInput[index] = .infinity
        case "negativeInfinity": finiteInput[index] = -.infinity
        default: throw DiarizationParityOracleError.invalidTensor("\(name): unsupported nonfinite patch kind \(kind)")
        }
    }
    try #require(finiteInput.indices.allSatisfy { index in
        suppliedPatches.contains { ($0["index"] as? Int) == index } || finiteInput[index].isFinite
    }, "Unpatched embedding coordinates must be finite")
    var storedInput = finiteInput
    for patch in suppliedPatches {
        storedInput[patch["index"] as! Int] = 0
    }
    let storedEmbeddings = (0..<3).map { row in
        Array(finiteInput[(row * dimension)..<((row + 1) * dimension)])
    }
    let embeddings = activeSlots.map { storedEmbeddings[$0] }
    let output = manager.clusterAssignments(
        vbxOutput: VBxOutput(
            gamma: gamma,
            pi: pi,
            hardClusters: [],
            centroids: [],
            numClusters: piSlots,
            elbos: [],
            wasAdjusted: false,
            originalClusterCount: nil
        ),
        trainingEmbeddings: centroids,
        embeddingFeatures: embeddings,
        initialClusters: initialClusters,
        chunkIndices: Array(repeating: 0, count: activeSlots.count)
    )
    try #require(output.centroids == centroids, "Manager must preserve supplied desired centroid coordinates for \(name)")
    try #require(output.centroids.count > 1, "Embedding case must enter constrained manager branch for \(name)")
    try #require(output.assignments.count == activeSlots.count, "Manager assignment count must match selected feature rows for \(name)")
    var expectedAssignments = Array(repeating: -2, count: 3)
    for (assignmentIndex, slot) in activeSlots.enumerated() {
        expectedAssignments[slot] = output.assignments[assignmentIndex]
    }

    return [
        "name": name,
        "construction": construction,
        "embeddings": try DiarizationParityOracle.tensor(storedInput, shape: [3, dimension]),
        "nonfinite": suppliedPatches,
        "activeSlots": activeSlots,
        "centroids": try DiarizationParityOracle.tensor(centroids.flatMap { $0 }, shape: [centroids.count, dimension]),
        "expectedAssignments": expectedAssignments,
    ]
}
