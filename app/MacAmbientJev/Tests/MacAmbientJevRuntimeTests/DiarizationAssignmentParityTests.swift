@available(macOS 14.0, *)
private func assignmentCentroidCase(
    manager: OfflineDiarizerManager,
    name: String,
    construction: String,
    training: [[Double]],
    gamma: [[Double]],
    pi: [Double]
) throws -> [String: Any] {
    try #require(!training.isEmpty, "Centroid case training must not be empty")
    let dimension = training[0].count
    try #require(dimension > 0 && training.allSatisfy { $0.count == dimension }, "Centroid case rows must have a common positive dimension")
    try #require(gamma.count == training.count && gamma.allSatisfy { $0.count == pi.count }, "Centroid case gamma must match training rows and pi slots")
    let activeSourceClusterIndices = pi.enumerated().compactMap { index, value in
        value > VBxOutput.activeClusterEpsilon ? index : nil
    }
    try #require(!activeSourceClusterIndices.isEmpty, "Centroid fixture must not use the manager's no-active-pi fallback")
    try #require(activeSourceClusterIndices.allSatisfy { source in gamma.contains { $0[source] > 0 } }, "Every active source cluster must have positive total gamma weight")
    let output = manager.clusterAssignments(
        vbxOutput: VBxOutput(
            gamma: gamma,
            pi: pi,
            hardClusters: [],
            centroids: [],
            numClusters: pi.count,
            elbos: [],
            wasAdjusted: false,
            originalClusterCount: nil
        ),
        trainingEmbeddings: training,
        embeddingFeatures: [],
        initialClusters: Array(repeating: 0, count: training.count),
        chunkIndices: []
    )
    try #require(output.centroids.count == activeSourceClusterIndices.count, "Manager centroid count must match active source pi count for \(name)")
    return [
        "name": name,
        "construction": construction,
        "trainingEmbeddings": try DiarizationParityOracle.tensor(training.flatMap { $0 }, shape: [training.count, dimension]),
        "gamma": try DiarizationParityOracle.tensor(gamma.flatMap { $0 }, shape: [gamma.count, pi.count]),
        "pi": try DiarizationParityOracle.tensor(pi, shape: [pi.count]),
        "expectedSourceClusterIndices": activeSourceClusterIndices,
        "expectedCentroids": try DiarizationParityOracle.tensor(output.centroids.flatMap { $0 }, shape: [output.centroids.count, dimension]),
    ]
}

